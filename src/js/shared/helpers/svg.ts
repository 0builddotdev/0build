export type SvgIconName = keyof typeof SVG_PATHS;

export function svgIconMarkup(name: SvgIconName, size: number = 16): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${SVG_PATHS[name]}</svg>`;
}

export function svgIcon(name: SvgIconName, size: number = 16): TemplateResult | undefined {
  const body = SVG_PATHS[name];

  if (!body) {
    return undefined;
  }

  return html`
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width="${size}"
      height="${size}"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      aria-hidden="true"
    >
      ${unsafeHTML(body)}
    </svg>
  `;
}
